#!/usr/bin/env node

const MultiStepTestRunner = require('../src/utils/multiStepTestRunner');
const logger = require('../src/utils/logger');

/**
 * Example: Multi-step registration với luồng phức tạp
 * 1. Điền thông tin cơ bản -> Click Tiếp tục
 * 2. Đợi verifyCaptcha nếu có  
 * 3. Đợi validation và redirect
 * 4. Đợi email gửi OTP
 * 5. Nhập OTP -> Verify
 * 6. Đăng ký thành công
 */

async function runMultiStepRegistration() {
  console.log('🚀 Starting multi-step registration test...\n');

  const testRunner = new MultiStepTestRunner({
    appUrl: 'https://your-registration-site.com',  // Thay URL thật của bạn
    headless: false,                               // Hiển thị browser để theo dõi
    screenshotOnFailure: true,
    validateInputs: true,
    
    // Timeouts cho từng bước
    validationTimeout: 15000,                      // 15s đợi validation
    otpEmailTimeout: 120000,                       // 2 phút đợi email OTP
    captchaTimeout: 30000,                         // 30s cho captcha
    
    // Flow options
    waitForOtpEmail: true,                         // Có đợi email OTP
    skipCaptcha: false,                            // Không skip captcha
    
    enableDatabase: true,
    enableRedis: true,
    cleanupAfterTest: true
  });

  try {
    await testRunner.initialize();

    // Test Case 1: Complete flow với tất cả parameters
    console.log('📝 Test 1: Complete multi-step flow');
    
    const userData = {
      email: 'test.multistep@example.com',
      password: 'MultiStep123@',
      confirmPassword: 'MultiStep123@',
      firstName: 'Multi',
      lastName: 'Step',
      username: 'multistep_user',
      phone: '0987654321',
      dateOfBirth: '15/06/1995',
      address: '123 Multi Step Street',
      city: 'Test City',
      postalCode: '12345'
    };

    const flowOptions = {
      captchaText: null,                           // Sẽ cần nhập manual hoặc có service
      otpCode: '123456',                           // OTP code (có thể lấy từ email service)
      waitForOtpEmail: true,
      skipCaptcha: false
    };

    const result = await testRunner.runCompleteRegistrationFlow(userData, flowOptions);
    
    console.log('✅ Test 1 result:', result.success ? 'PASSED' : 'FAILED');
    console.log('📋 Steps completed:');
    result.steps.forEach((step, index) => {
      console.log(`  ${index + 1}. ${step.name}: ${step.success ? '✅' : '❌'} ${step.message}`);
    });

    if (!result.success) {
      console.log('❌ Errors:', result.errors);
    }

  } catch (error) {
    console.error('❌ Test failed:', error.message);
  } finally {
    await testRunner.cleanup();
    console.log('\n🧹 Cleanup completed');
  }
}

// Step-by-step debugging mode
async function runStepByStepMode() {
  console.log('🔍 Running step-by-step debug mode...\n');

  const testRunner = new MultiStepTestRunner({
    appUrl: 'https://your-registration-site.com',
    headless: false,                               // PHẢI false để xem từng bước
    screenshotOnFailure: true
  });

  try {
    await testRunner.initialize();

    const userData = {
      email: 'debug.step@example.com',
      password: 'DebugStep123@',
      firstName: 'Debug',
      lastName: 'Step',
      username: 'debug_step',
      phone: '0987654321'
    };

    const options = {
      captchaText: null,                           // Để null sẽ đợi manual input
      otpCode: null,                               // Để null sẽ đợi manual input
      waitForOtpEmail: true,
      skipCaptcha: false
    };

    console.log('🎯 Starting step-by-step mode...');
    console.log('ℹ️  Browser sẽ pause giữa các bước để bạn quan sát');
    console.log('ℹ️  Bạn có thể manual solve captcha và nhập OTP');

    const result = await testRunner.runStepByStep(userData, options);
    console.log('🎉 Step-by-step completed:', result);

  } catch (error) {
    console.error('❌ Step-by-step failed:', error.message);
  } finally {
    await testRunner.cleanup();
  }
}

// Auto-generated data test
async function runAutoGeneratedTest() {
  console.log('🤖 Running auto-generated data test...\n');

  const testRunner = new MultiStepTestRunner({
    appUrl: 'https://your-registration-site.com',
    headless: true,
    waitForOtpEmail: false,                        // Skip OTP để test nhanh
    skipCaptcha: true                              // Skip captcha để test tự động
  });

  try {
    await testRunner.initialize();

    // Không truyền userData - sẽ tự generate
    const result = await testRunner.runCompleteRegistrationFlow();
    
    console.log('🤖 Auto-generated test result:', result.success ? 'PASSED' : 'FAILED');
    console.log('📧 Generated email:', result.userData?.email);
    console.log('📱 Generated phone:', result.userData?.phone);

  } catch (error) {
    console.error('❌ Auto-generated test failed:', error.message);
  } finally {
    await testRunner.cleanup();
  }
}

// Main menu
async function main() {
  const args = process.argv.slice(2);
  
  if (args.includes('--step-by-step') || args.includes('-s')) {
    await runStepByStepMode();
  } else if (args.includes('--auto') || args.includes('-a')) {
    await runAutoGeneratedTest();
  } else {
    await runMultiStepRegistration();
  }
}

// Usage instructions
if (process.argv.includes('--help') || process.argv.includes('-h')) {
  console.log(`
🔧 Multi-Step Registration Test

Usage:
  node examples/multiStepRegistration.js                    # Normal flow
  node examples/multiStepRegistration.js --step-by-step     # Debug mode (pause between steps)
  node examples/multiStepRegistration.js --auto             # Auto-generated data

Options:
  -s, --step-by-step    Run in step-by-step debug mode
  -a, --auto           Run with auto-generated data
  -h, --help           Show this help

Configuration:
  1. Update appUrl in the script to your registration page
  2. Configure selectors in MultiStepRegisterPage.js if needed
  3. Set up captcha service or manual solving
  4. Set up OTP email service or manual input

Flow:
  1. Fill basic info → Click Continue
  2. Handle Captcha (if exists)
  3. Wait for validation & redirect
  4. Wait for OTP email
  5. Enter OTP → Verify
  6. Registration success
  `);
  process.exit(0);
}

// Run if called directly
if (require.main === module) {
  main()
    .then(() => {
      console.log('\n✅ Script completed successfully');
      process.exit(0);
    })
    .catch((error) => {
      console.error('\n❌ Script failed:', error.message);
      process.exit(1);
    });
}

module.exports = { 
  runMultiStepRegistration, 
  runStepByStepMode, 
  runAutoGeneratedTest 
};
